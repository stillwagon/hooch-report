// Measure Buford pulse travel times from USGS history and write src/data/travel.js.
// Usage: npm run calibrate -- [days=120]
// Runs in the "Calibrate travel times" workflow (this needs network access to USGS).
import { writeFileSync } from "node:fs";
import { GAUGES } from "../src/data/river.js";
import { parseOgc, parseLegacy } from "../src/fetchers/usgs.js";
import { findReleases, measureLag } from "../src/lib/calibrate.js";

const DAYS = +(process.argv[2] ?? 120);
const end = new Date(), start = new Date(+end - DAYS * 864e5);
const MIN_SAMPLES = 5;

async function ogcHistory(id) {
  const q = new URLSearchParams({ f: "json", monitoring_location_id: `USGS-${id}`, parameter_code: "00060", time: `${start.toISOString()}/${end.toISOString()}`, limit: "10000", skipGeometry: "true" });
  let url = `https://api.waterdata.usgs.gov/ogcapi/v0/collections/continuous/items?${q}`;
  const rows = [];
  for (let page = 0; url && page < 50; page++) {
    const r = await fetch(url); if (!r.ok) throw new Error(`OGC ${r.status}`);
    const j = await r.json();
    rows.push(...parseOgc(j));
    url = j.links?.find(l => l.rel === "next")?.href ?? null;
  }
  return rows.sort((a, b) => a.t - b.t);
}

async function legacyHistory(id) {
  const r = await fetch(`https://waterservices.usgs.gov/nwis/iv/?format=json&sites=${id}&parameterCd=00060&startDT=${start.toISOString().slice(0, 10)}&endDT=${end.toISOString().slice(0, 10)}`);
  if (!r.ok) throw new Error(`legacy ${r.status}`);
  return Object.values(parseLegacy(await r.json()))[0]?.discharge ?? [];
}

async function history(key) {
  try { const s = await ogcHistory(GAUGES[key].id); if (s.length) return { s, src: "OGC" }; } catch (e) { console.warn(key, e.message); }
  return { s: await legacyHistory(GAUGES[key].id), src: "legacy" };
}

const data = {};
for (const k of Object.keys(GAUGES)) { data[k] = await history(k); console.log(`${k}: ${data[k].s.length} samples (${data[k].src})`); }

const releases = findReleases(data.bufordDam.s);
console.log(`Buford releases found: ${releases.length}`);

const gaugeLagMin = { bufordDam: 0 }, gaugeTailLagMin = { bufordDam: 0 }, samples = {};
let calibrated = true;
for (const k of Object.keys(GAUGES).filter(k => k !== "bufordDam")) {
  const m = measureLag(data.bufordDam.s, data[k].s, releases, GAUGES[k].lag);
  samples[k] = m;
  if (m.rise.n >= MIN_SAMPLES) gaugeLagMin[k] = m.rise.median; else { gaugeLagMin[k] = GAUGES[k].lag; calibrated = false; }
  gaugeTailLagMin[k] = m.fall.n >= MIN_SAMPLES ? m.fall.median : gaugeLagMin[k];
  console.log(`${k}: rise ${JSON.stringify(m.rise)} fall ${JSON.stringify(m.fall)} (estimate was ${GAUGES[k].lag})`);
}

const out = { calibrated, note: `Measured ${end.toISOString().slice(0, 10)} from ${DAYS} days of USGS data, ${releases.length} releases. Lags are median half-height crossing times.${calibrated ? "" : ` Some gauges had fewer than ${MIN_SAMPLES} clean releases; their estimates are kept and calibration stays off.`}`, gaugeLagMin, gaugeTailLagMin, samples };
writeFileSync(new URL("../src/data/travel.js", import.meta.url),
  `// Pulse travel times from Buford Dam. Generated by \`npm run calibrate\`; edit by hand\n// only to restore defaults. While \`calibrated\` is false, per-spot estimates in\n// SPOTS.pulse are used and the UI labels travel times as estimates.\nexport default ${JSON.stringify(out, null, 2)};\n`);

const table = ["| Gauge | Estimate | Rise lag (median, IQR, n) | Fall lag (median, n) |", "|---|---|---|---|",
  ...Object.entries(samples).map(([k, m]) => `| ${GAUGES[k].name} | ${GAUGES[k].lag} | ${m.rise.n ? `${m.rise.median} (${m.rise.p25}–${m.rise.p75}), n=${m.rise.n}` : "n=0"} | ${m.fall.n ? `${m.fall.median}, n=${m.fall.n}` : "n=0"} |`)].join("\n");
console.log(table);
if (process.env.GITHUB_STEP_SUMMARY) writeFileSync(process.env.GITHUB_STEP_SUMMARY, `### Travel-time calibration\n${releases.length} releases in ${DAYS} days. calibrated=${calibrated}\n\n${table}\n`, { flag: "a" });
